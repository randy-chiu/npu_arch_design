def _append_job_id_defines(lines: list[str], jobs: list[dict]) -> None:
    first_by_workload: dict[str, int] = {}
    for job in jobs:
        first_by_workload.setdefault(job["workload"], job["job_id"])
    lines.append("")
    lines.append("/* Descriptor job identity values also consumed by workload_manifest.json. */")
    for workload, first_id in first_by_workload.items():
        macro = workload.upper()
        suffix = "_BASE" if sum(job["workload"] == workload for job in jobs) > 1 else ""
        lines.append(f"#define JOB_ID_{macro}{suffix} {first_id}u")
    lines.append("")


def _append_transformer_runtime_plan_data(lines: list[str], transformer_micro: dict) -> None:
    plans = transformer_micro.get("attention_plans", [])
    if not plans:
        lines.append("#define TRANSFORMER_ATTENTION_RUNTIME_JOBS 0u")
        lines.append("")
        return
    if len(plans) != 1:
        raise ValueError("current firmware smoke supports one attention runtime plan")
    plan = plans[0]
    if plan.get("execution_state") != "executable":
        raise ValueError(
            f"firmware cannot emit non-executable attention plan {plan['attention_group']}: "
            f"{plan.get('execution_state')}"
        )
    jobs = plan["runtime_jobs"]
    lines.append("#define TRANSFORMER_RUNTIME_STAGE_QK 1u")
    lines.append("#define TRANSFORMER_RUNTIME_STAGE_SCALE_MASK 2u")
    lines.append("#define TRANSFORMER_RUNTIME_STAGE_SOFTMAX 3u")
    lines.append("#define TRANSFORMER_RUNTIME_STAGE_PV 4u")
    lines.append("#define TRANSFORMER_RUNTIME_CHECK_EXACT 1u")
    lines.append("#define TRANSFORMER_RUNTIME_CHECK_ABS_TOL 2u")
    lines.append(f"#define TRANSFORMER_ATTENTION_RUNTIME_JOBS {len(jobs)}u")
    lines.append("")
    lines.append("typedef struct {")
    lines.append("    uint32_t stage;")
    lines.append("    uint32_t op_type;")
    lines.append("    uint32_t job_id;")
    lines.append("    uint32_t check_policy;")
    lines.append("} transformer_runtime_job_t;")
    lines.append("")
    lines.append(
        f"static const transformer_runtime_job_t {plan['attention_group']}_runtime_jobs[{len(jobs)}] = {{"
    )
    for job in jobs:
        stage_macro = {
            "qk": "TRANSFORMER_RUNTIME_STAGE_QK",
            "scale_mask": "TRANSFORMER_RUNTIME_STAGE_SCALE_MASK",
            "softmax": "TRANSFORMER_RUNTIME_STAGE_SOFTMAX",
            "pv": "TRANSFORMER_RUNTIME_STAGE_PV",
        }[job["stage_id"]]
        op_macro = {
            "matmul_k_stream": "SOC_NPU_JOB_OP_MATMUL_K_STREAM",
            "attention_scale_mask_v1": "SOC_NPU_JOB_OP_ATTENTION_SCALE_MASK_V1",
            "attention_softmax_v1": "SOC_NPU_JOB_OP_ATTENTION_SOFTMAX_V1",
            "matmul_u16s8_q15": "SOC_NPU_JOB_OP_MATMUL_U16S8_Q15",
        }[job["descriptor_op"]]
        check_macro = {
            "exact": "TRANSFORMER_RUNTIME_CHECK_EXACT",
            "absolute_tolerance": "TRANSFORMER_RUNTIME_CHECK_ABS_TOL",
        }[job["check_policy"]]
        lines.append(f"    {{{stage_macro}, {op_macro}, {job['job_id_symbol']}, {check_macro}}},")
    lines.append("};")
    lines.append("")


def _append_2d_array(lines: list[str], symbol: str, values: list, bits: int) -> None:
    if symbol == "digits_tile_n_offsets":
        flat_rows = values
        row_len = len(values[0])
    else:
        flat_rows = [_flatten(item) for item in values]
        row_len = len(flat_rows[0])
    lines.append(f"static const uint32_t {symbol}[{len(flat_rows)}][{row_len}] = {{")
    mask = (1 << bits) - 1
    for row in flat_rows:
        lines.append("    {" + ", ".join(f"0x{(int(value) & mask):08x}u" for value in row) + "},")
    lines.append("};")
    lines.append("")


def _append_3d_array(lines: list[str], symbol: str, values: list, bits: int) -> None:
    flat_planes = [[_flatten(row) for row in plane] for plane in values]
    rows = len(flat_planes[0])
    cols = len(flat_planes[0][0])
    mask = (1 << bits) - 1
    lines.append(f"static const uint32_t {symbol}[{len(flat_planes)}][{rows}][{cols}] = {{")
    for plane in flat_planes:
        lines.append("    {")
        for row in plane:
            lines.append("        {" + ", ".join(f"0x{(int(value) & mask):08x}u" for value in row) + "},")
        lines.append("    },")
    lines.append("};")
    lines.append("")


def _pad_chunks(chunks: list[list[int]], max_chunks: int, tile_words: int) -> list[list[int]]:
    padded = [list(chunk) for chunk in chunks]
    while len(padded) < max_chunks:
        padded.append([0 for _ in range(tile_words)])
    return padded


def _append_flat_array(lines: list[str], symbol: str, values: list[int], bits: int) -> None:
    mask = (1 << bits) - 1
    lines.append(f"static const uint32_t {symbol}[{len(values)}] = {{")
    for value in values:
        lines.append(f"    0x{(int(value) & mask):08x}u,")
    lines.append("};")
    lines.append("")


def _flatten(value):
    out = []
    for item in value:
        if isinstance(item, list):
            out.extend(_flatten(item))
        else:
            out.append(item)
    return out


