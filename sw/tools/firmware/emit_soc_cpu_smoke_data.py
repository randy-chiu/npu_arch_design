"""Emit C data arrays for the SoC CPU smoke firmware from RTL fixtures."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


_REPO_ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(_REPO_ROOT / "sw" / "tools"))

from npu_phase0.digits_classifier import (  # noqa: E402
    CLASS_COLUMNS,
    REAL_CLASSES,
    classifier_inputs_from_image,
    lower_classifier_to_rtl_tiles,
    predict_label,
    reference_logits_from_image,
)
from npu_phase0.golden import matmul  # noqa: E402
from npu_compiler.k_stream import plan_matmul_k_stream  # noqa: E402
from npu_phase0.real_mnist_cnn import (  # noqa: E402
    MODEL_README_PATH,
    MODEL_WEIGHTS_PATH,
    TEST_IMAGES_PATH,
    TEST_LABELS_PATH,
    fc1_npu_inputs_from_flat,
    fc2_npu_inputs_from_activation,
    forward_intermediates,
    load_mnist_images,
    load_mnist_labels,
    load_safetensors_f32,
    lower_fc2_to_rtl_tiles,
    numpy_available,
    predict,
)


DATASETS = (
    ("matmul_a", "matmul_a.hex"),
    ("matmul_b", "matmul_b.hex"),
    ("matmul_expected_c", "matmul_expected_c.hex"),
    ("matmul_program", "matmul_program.hex"),
    ("softmax_x", "softmax_x.hex"),
    ("softmax_expected_y", "softmax_expected_y.hex"),
    ("softmax_program", "softmax_program.hex"),
)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--fixtures", type=Path, default=Path("build/rtl_fixture"))
    parser.add_argument("--out", type=Path, default=Path("build/firmware/soc_cpu_smoke_data.h"))
    parser.add_argument("--manifest-out", type=Path, default=Path("build/perf/workload_manifest.json"))
    args = parser.parse_args()

    lines = [
        "/* Generated by sw/tools/firmware/emit_soc_cpu_smoke_data.py. */",
        "/* Do not edit by hand. */",
        "#ifndef SOC_CPU_SMOKE_DATA_H",
        "#define SOC_CPU_SMOKE_DATA_H",
        "",
        "#include <stdint.h>",
        "",
    ]
    for symbol, filename in DATASETS:
        values = _read_hex(args.fixtures / filename)
        lines.append(f"#define {symbol.upper()}_LEN {len(values)}u")
        lines.append(f"static const uint32_t {symbol}[{len(values)}] = {{")
        for value in values:
            lines.append(f"    0x{value & 0xFFFF_FFFF:08x}u,")
        lines.append("};")
        lines.append("")

    digits_jobs = _append_digits_classifier_data(lines)
    fc1_tile_jobs = _append_real_mnist_cnn_fc1_tile_data(lines)
    fc1_k_stream_jobs = _append_real_mnist_cnn_fc1_k_stream_data(lines)
    fc1_full_jobs, fc1_full_k_chunks = _append_real_mnist_cnn_fc1_full_k_stream_data(lines)
    fc2_jobs = _append_real_mnist_cnn_fc2_data(lines)
    lines.append("#endif")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    _write_workload_manifest(
        args.manifest_out,
        digits_jobs,
        fc1_tile_jobs if fc2_jobs else 0,
        fc1_k_stream_jobs if fc2_jobs else 0,
        fc1_full_jobs if fc2_jobs else 0,
        fc1_full_k_chunks if fc2_jobs else 0,
        fc2_jobs,
    )


def _read_hex(path: Path) -> list[int]:
    return [int(line.strip(), 16) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def _append_digits_classifier_data(lines: list[str]) -> int:
    image_path = _REPO_ROOT / "test/assets/digits_realistic/digit_2_gray.pgm"
    inputs = classifier_inputs_from_image(image_path)
    jobs = lower_classifier_to_rtl_tiles(inputs)
    logits = reference_logits_from_image(image_path)
    expected_label = predict_label(logits)

    lines.append("#define DIGITS_TILE_COUNT 16u")
    lines.append("#define DIGITS_TILE_WORDS 64u")
    lines.append(f"#define DIGITS_LOGITS_WORDS {len(logits) * len(logits[0])}u")
    lines.append(f"#define DIGITS_CLASS_COUNT {REAL_CLASSES}u")
    lines.append(f"#define DIGITS_CLASS_COLUMNS {CLASS_COLUMNS}u")
    lines.append(f"#define DIGITS_EXPECTED_LABEL {expected_label}u")
    lines.append("")

    _append_2d_array(lines, "digits_tile_n_offsets", [[job["n_offset"] for job in jobs]], bits=32)
    _append_2d_array(lines, "digits_tile_a", [job["inputs"]["A"] for job in jobs], bits=8)
    _append_2d_array(lines, "digits_tile_b", [job["inputs"]["B"] for job in jobs], bits=8)
    _append_flat_array(lines, "digits_expected_logits", _flatten(logits), bits=32)
    return len(jobs)


def _real_mnist_external_available() -> bool:
    return (
        numpy_available()
        and (_REPO_ROOT / MODEL_WEIGHTS_PATH).exists()
        and (_REPO_ROOT / MODEL_README_PATH).exists()
        and (_REPO_ROOT / TEST_IMAGES_PATH).exists()
        and (_REPO_ROOT / TEST_LABELS_PATH).exists()
    )


def _append_real_mnist_cnn_fc1_tile_data(lines: list[str]) -> int:
    if not _real_mnist_external_available():
        lines.append("#define REAL_MNIST_CNN_FC1_TILE_ENABLED 0u")
        lines.append("")
        return 0

    weights = load_safetensors_f32(_REPO_ROOT / MODEL_WEIGHTS_PATH)
    images = load_mnist_images(_REPO_ROOT / TEST_IMAGES_PATH)
    labels = load_mnist_labels(_REPO_ROOT / TEST_LABELS_PATH)
    sample_index = 0
    expected_label = int(labels[sample_index])
    original_prediction = predict(images[sample_index], weights)
    if original_prediction != expected_label:
        raise ValueError(f"MNIST sample {sample_index} predicts {original_prediction}, expected {expected_label}")

    intermediates = forward_intermediates(images[sample_index], weights)
    npu_inputs = fc1_npu_inputs_from_flat(intermediates["flat"], weights)
    plan = plan_matmul_k_stream(
        npu_inputs["A"],
        npu_inputs["W"],
        n_offset=0,
        max_chunks=1,
        require_nonzero=True,
    )
    chunk = plan["chunks"][0]

    lines.append("#define REAL_MNIST_CNN_FC1_TILE_ENABLED 1u")
    lines.append(f"#define REAL_MNIST_CNN_FC1_TILE_SAMPLE_INDEX {sample_index}u")
    lines.append("#define REAL_MNIST_CNN_FC1_TILE_WORDS 64u")
    lines.append(f"#define REAL_MNIST_CNN_FC1_TILE_K_OFFSET {chunk['k_offset']}u")
    lines.append(f"#define REAL_MNIST_CNN_FC1_TILE_N_OFFSET {plan['n_offset']}u")
    lines.append("")

    _append_flat_array(lines, "real_mnist_cnn_fc1_tile_a", _flatten(chunk["a_tile"]), bits=8)
    _append_flat_array(lines, "real_mnist_cnn_fc1_tile_b", _flatten(chunk["b_tile"]), bits=8)
    _append_flat_array(lines, "real_mnist_cnn_fc1_tile_expected_c", _flatten(chunk["expected_tile"]), bits=32)
    return 1


