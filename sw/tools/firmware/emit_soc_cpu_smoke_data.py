def _write_workload_manifest(
    path: Path,
    digits_jobs: int,
    fc1_tile_jobs: int,
    fc1_k_stream_jobs: int,
    fc1_full_jobs: int,
    fc1_full_k_chunks: int,
    fc2_jobs: int,
    transformer_micro: dict | None = None,
    workload_profile: str = "quick",
    jobs: list[dict] | None = None,
) -> None:
    if jobs is None:
        jobs = _build_workload_jobs(
            digits_jobs,
            fc1_tile_jobs,
            fc1_k_stream_jobs,
            fc1_full_jobs,
            fc2_jobs,
            transformer_micro["executable_workloads"] if transformer_micro else [],
        )
    transformer_micro = transformer_micro or {"executable_workloads": [], "model_only_workloads": []}
    transformer_metadata = {
        item["name"]: {"kind": item["kind"], "metadata": item["metadata"]}
        for item in transformer_micro["executable_workloads"]
    }
    transformer_metadata.update(
        {
            item["name"]: {"kind": item["kind"], "metadata": item["metadata"]}
            for item in transformer_micro["model_only_workloads"]
        }
    )
    manifest_id = f"soc_cpu_smoke_{workload_profile.replace('-', '_')}_v0"
    manifest = {
        "schema": "npu_workload_manifest_v0",
        "manifest_id": manifest_id,
        "run_name": "soc_cpu_smoke",
        "generated_by": "sw/tools/firmware/emit_soc_cpu_smoke_data.py",
        "workload_profile": workload_profile,
        "workload_metadata": {
            "operator_smoke_matmul": {"kind": "operator_smoke"},
            "digits_linear_classifier": {
                "kind": "model",
                "metadata": {
                    "input": "test/assets/digits_realistic/digit_2_gray.pgm",
                    "graph": "test/graphs/digits_classifier.json",
                    "tile_graph": "test/graphs/digits_classifier_rtl_tile.json",
                    "tile_jobs": digits_jobs,
                    "description": "8x8 grayscale digit image, tiled matmul regression with CPU-side accumulation",
                },
            },
            "real_mnist_cnn_fc1_tile0": {
                "kind": "model_layer_tile",
                "metadata": {"tile_jobs": fc1_tile_jobs},
            },
            "real_mnist_cnn_fc1_k_stream_smoke": {
                "kind": "model_layer_tile",
                "metadata": {"tile_jobs": fc1_k_stream_jobs},
            },
            "real_mnist_cnn_fc1_full_k_stream_layer": {
                "kind": "model_layer",
                "metadata": {
                    "tile_jobs": fc1_full_jobs,
                    "k_chunks": fc1_full_k_chunks,
                    "comparison_baseline": {
                        "id": "npu_v0_a2_serial_k_stream_proxy",
                        "cycles_per_job": 58784
                    },
                },
            },
            "real_mnist_cnn_fc2": {
                "kind": "model_layer",
                "metadata": {"tile_jobs": fc2_jobs},
            },
            **transformer_metadata,
        },
        "jobs": jobs,
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")


def _build_workload_jobs(
    digits_jobs: int,
    fc1_tile_jobs: int,
    fc1_k_stream_jobs: int,
    fc1_full_jobs: int,
    fc2_jobs: int,
    transformer_workloads: list[dict] | None = None,
) -> list[dict]:
    jobs: list[dict] = []

    def add(workload: str, op: str, role: str, count: int, tiled: bool = False) -> None:
        for tile_id in range(count):
            item = {
                "job_id": len(jobs) + 1,
                "workload": workload,
                "op": op,
                "role": role,
            }
            if tiled:
                item["tile_id"] = tile_id
            jobs.append(item)

    add("operator_smoke_matmul", "matmul", "smoke", 1)
    add("operator_smoke_vector_tile_vadd", "desc_vector_tile_v1", "smoke", 1)
    add("digits_linear_classifier", "matmul", "regression", digits_jobs, tiled=True)
    add("real_mnist_cnn_fc1_tile0", "matmul", "regression", fc1_tile_jobs, tiled=True)
    add("real_mnist_cnn_fc1_k_stream_smoke", "matmul_k_stream", "regression", fc1_k_stream_jobs, tiled=True)
    add("real_mnist_cnn_fc1_full_k_stream_layer", "matmul_k_stream", "regression", fc1_full_jobs, tiled=True)
    add("real_mnist_cnn_fc2", "matmul", "regression", fc2_jobs, tiled=True)
    for workload in transformer_workloads or []:
        if workload["op"] == "block_attention_head_group":
            for job in workload["stage_jobs"]:
                jobs.append(
                    {
                        "job_id": len(jobs) + 1,
                        "workload": workload["name"],
                        "op": job["op"],
                        "role": workload["role"],
                        "tile_id": job["stage_job_index"],
                        "attention_head": job["head"],
                        "attention_stage": job["stage"],
                    }
                )
            continue
        job_op = {
            "block_matmul_k_stream_group": "matmul_k_stream",
            "block_desc_vector_tile_group": "desc_vector_tile_v1",
        }.get(workload["op"], workload["op"])
        add(workload["name"], job_op, workload["role"], len(workload.get("tile_jobs", [None])), tiled=True)
    return jobs


def _append_transformer_micro_data(lines: list[str]) -> dict:
    transformer_micro = generate_transformer_micro_fixtures()
    executable = transformer_micro["executable_workloads"]
    lines.append("#define TRANSFORMER_MICRO_ENABLED 1u")
    lines.append(f"#define TRANSFORMER_MICRO_EXECUTABLE_WORKLOADS {len(executable)}u")
    lines.append("")
    for workload in executable:
        macro = workload["name"].upper()
        if workload["op"] in ("matmul_k_stream", "matmul_u16s8_q15"):
            lines.append(f"#define {macro}_CHUNKS {workload['k_chunks']}u")
            lines.append(f"#define {macro}_TILE_WORDS {workload['tile_words']}u")
            lines.append("")
            _append_2d_array(lines, f"{workload['name']}_a", workload["a_stream"], bits=int(workload.get("a_bits", 8)))
            _append_2d_array(lines, f"{workload['name']}_b", workload["b_stream"], bits=8)
            _append_flat_array(lines, f"{workload['name']}_expected_c", workload["expected_c"], bits=32)
        elif workload["op"] == "block_matmul_k_stream_group":
            max_chunks = int(workload["max_k_chunks"])
            tile_words = int(workload["tile_words"])
            tile_jobs = workload["tile_jobs"]
            lines.append(f"#define {macro}_TILE_JOBS {len(tile_jobs)}u")
            lines.append(f"#define {macro}_MAX_CHUNKS {max_chunks}u")
            lines.append(f"#define {macro}_TILE_WORDS {tile_words}u")
            lines.append("")
            _append_flat_array(lines, f"{workload['name']}_k_chunks", [job["k_chunks"] for job in tile_jobs], bits=32)
            _append_3d_array(
                lines,
                f"{workload['name']}_a",
                [_pad_chunks(job["a_stream"], max_chunks, tile_words) for job in tile_jobs],
                bits=8,
            )
            _append_3d_array(
                lines,
                f"{workload['name']}_b",
                [_pad_chunks(job["b_stream"], max_chunks, tile_words) for job in tile_jobs],
                bits=8,
            )
            _append_2d_array(lines, f"{workload['name']}_expected_c", [job["expected_c"] for job in tile_jobs], bits=32)
        elif workload["op"] == "block_desc_vector_tile_group":
            tile_words = int(workload["tile_words"])
            tile_jobs = workload["tile_jobs"]
            lines.append(f"#define {macro}_TILE_JOBS {len(tile_jobs)}u")
            lines.append(f"#define {macro}_TILE_WORDS {tile_words}u")
            lines.append("")
            _append_2d_array(lines, f"{workload['name']}_input0", [job["input0"] for job in tile_jobs], bits=32)
            _append_2d_array(lines, f"{workload['name']}_input1", [job["input1"] for job in tile_jobs], bits=32)
            if any("program_select" in job for job in tile_jobs):
                select_values = [0 if job.get("program_select") == "src0" else 1 for job in tile_jobs]
                _append_flat_array(lines, f"{workload['name']}_program_select", select_values, bits=32)
            _append_2d_array(
                lines,
                f"{workload['name']}_expected_output",
                [job["expected_output"] for job in tile_jobs],
                bits=32,
            )
        elif workload["op"] == "block_attention_head_group":
            heads = workload["heads"]
            lines.append(f"#define {macro}_HEADS {len(heads)}u")
            lines.append(f"#define {macro}_STAGE_JOBS {len(workload['stage_jobs'])}u")
            lines.append(f"#define {macro}_TILE_WORDS {workload['tile_words']}u")
            lines.append(f"#define {macro}_MASK_WORDS {len(workload['row_mask_words'])}u")
            lines.append("")
            qk_jobs = [job for job in workload["stage_jobs"] if job["stage"] == "qk"]
            scale_jobs = [job for job in workload["stage_jobs"] if job["stage"] == "scale_mask"]
            softmax_jobs = [job for job in workload["stage_jobs"] if job["stage"] == "softmax"]
            pv_jobs = [job for job in workload["stage_jobs"] if job["stage"] == "pv"]
            _append_flat_array(lines, f"{workload['name']}_row_mask_words", workload["row_mask_words"], bits=32)
            _append_2d_array(lines, f"{workload['name']}_qk_a", [job["a_stream"][0] for job in qk_jobs], bits=8)
            _append_2d_array(lines, f"{workload['name']}_qk_b", [job["b_stream"][0] for job in qk_jobs], bits=8)
            _append_2d_array(lines, f"{workload['name']}_qk_expected", [job["expected_output"] for job in qk_jobs], bits=32)
            _append_2d_array(lines, f"{workload['name']}_scale_expected", [job["expected_output"] for job in scale_jobs], bits=32)
            _append_2d_array(lines, f"{workload['name']}_softmax_expected", [job["expected_output"] for job in softmax_jobs], bits=32)
            _append_2d_array(lines, f"{workload['name']}_pv_b", [job["b_stream"][0] for job in pv_jobs], bits=8)
            _append_2d_array(lines, f"{workload['name']}_pv_expected", [job["expected_output"] for job in pv_jobs], bits=32)
        elif workload["op"] == "attention_softmax_v1":
            lines.append(f"#define {macro}_X_WORDS {workload['x_words']}u")
            lines.append(f"#define {macro}_Y_WORDS {workload['y_words']}u")
            lines.append("")
            _append_flat_array(lines, f"{workload['name']}_x", workload["x"], bits=32)
            _append_flat_array(lines, f"{workload['name']}_expected_y", workload["expected_y"], bits=32)
        elif workload["op"] == "attention_scale_mask_v1":
            lines.append(f"#define {macro}_SCORE_WORDS {workload['score_words']}u")
            lines.append(f"#define {macro}_MASK_WORDS {len(workload['row_mask_words'])}u")
            lines.append("")
            _append_flat_array(lines, f"{workload['name']}_input_scores", workload["input_scores"], bits=32)
            _append_flat_array(lines, f"{workload['name']}_expected_scores", workload["expected_scores"], bits=32)
            _append_flat_array(lines, f"{workload['name']}_row_mask_words", workload["row_mask_words"], bits=32)
        else:
            raise ValueError(f"unsupported executable transformer op {workload['op']!r}")
    return transformer_micro


def _append_vector_tile_smoke_data(lines: list[str]) -> None:
    lhs = [1000 + lane for lane in range(8)]
    rhs = [-17 - lane for lane in range(8)]
    expected = [lhs[lane] + rhs[lane] for lane in range(8)]
    lines.append("#define VECTOR_TILE_VADD_WORDS 8u")
    lines.append("")
    _append_flat_array(lines, "vector_tile_vadd_lhs", lhs, bits=32)
    _append_flat_array(lines, "vector_tile_vadd_rhs", rhs, bits=32)
    _append_flat_array(lines, "vector_tile_vadd_expected", expected, bits=32)


