def _append_real_mnist_cnn_fc1_full_k_stream_data(lines: list[str]) -> tuple[int, int]:
    if not _real_mnist_external_available():
        lines.append("#define REAL_MNIST_CNN_FC1_FULL_K_STREAM_ENABLED 0u")
        lines.append("")
        return 0, 0

    weights = load_safetensors_f32(_REPO_ROOT / MODEL_WEIGHTS_PATH)
    images = load_mnist_images(_REPO_ROOT / TEST_IMAGES_PATH)
    labels = load_mnist_labels(_REPO_ROOT / TEST_LABELS_PATH)
    sample_index = 0
    expected_label = int(labels[sample_index])
    original_prediction = predict(images[sample_index], weights)
    if original_prediction != expected_label:
        raise ValueError(f"MNIST sample {sample_index} predicts {original_prediction}, expected {expected_label}")

    intermediates = forward_intermediates(images[sample_index], weights)
    npu_inputs = fc1_npu_inputs_from_flat(intermediates["flat"], weights)
    tile_n = 8
    tile_count = npu_inputs["padded_columns"] // tile_n
    plans = [
        plan_matmul_k_stream(npu_inputs["A"], npu_inputs["W"], n_offset=tile * tile_n)
        for tile in range(tile_count)
    ]
    first_plan = plans[0]

    lines.append("#define REAL_MNIST_CNN_FC1_FULL_K_STREAM_ENABLED 1u")
    lines.append(f"#define REAL_MNIST_CNN_FC1_FULL_K_STREAM_SAMPLE_INDEX {sample_index}u")
    lines.append(f"#define REAL_MNIST_CNN_FC1_FULL_K_STREAM_TILE_COUNT {tile_count}u")
    lines.append(f"#define REAL_MNIST_CNN_FC1_FULL_K_STREAM_CHUNKS {first_plan['k_chunks']}u")
    lines.append("#define REAL_MNIST_CNN_FC1_FULL_K_STREAM_TILE_WORDS 64u")
    lines.append(f"#define REAL_MNIST_CNN_FC1_FULL_K_STREAM_REAL_COLUMNS {npu_inputs['real_columns']}u")
    lines.append(f"#define REAL_MNIST_CNN_FC1_FULL_K_STREAM_PADDED_COLUMNS {npu_inputs['padded_columns']}u")
    lines.append("")

    _append_flat_array(lines, "real_mnist_cnn_fc1_full_k_stream_n_offsets", [plan["n_offset"] for plan in plans], bits=32)
    _append_flat_array(lines, "real_mnist_cnn_fc1_full_k_stream_k_offsets", first_plan["k_offsets"], bits=32)
    _append_2d_array(lines, "real_mnist_cnn_fc1_full_k_stream_a", first_plan["a_stream"], bits=8)
    _append_3d_array(lines, "real_mnist_cnn_fc1_full_k_stream_b", [plan["b_stream"] for plan in plans], bits=8)
    _append_2d_array(
        lines,
        "real_mnist_cnn_fc1_full_k_stream_expected_c",
        [plan["expected_c"] for plan in plans],
        bits=32,
    )
    return tile_count, first_plan["k_chunks"]


def _append_real_mnist_cnn_fc2_data(lines: list[str]) -> int:
    if not _real_mnist_external_available():
        lines.append("#define REAL_MNIST_CNN_FC2_ENABLED 0u")
        lines.append("")
        return 0

    weights = load_safetensors_f32(_REPO_ROOT / MODEL_WEIGHTS_PATH)
    images = load_mnist_images(_REPO_ROOT / TEST_IMAGES_PATH)
    labels = load_mnist_labels(_REPO_ROOT / TEST_LABELS_PATH)
    sample_index = 0
    expected_label = int(labels[sample_index])
    original_prediction = predict(images[sample_index], weights)
    if original_prediction != expected_label:
        raise ValueError(f"MNIST sample {sample_index} predicts {original_prediction}, expected {expected_label}")

    intermediates = forward_intermediates(images[sample_index], weights)
    npu_inputs = fc2_npu_inputs_from_activation(intermediates["fc1_relu"], weights)
    jobs = lower_fc2_to_rtl_tiles(npu_inputs)
    acc = matmul(npu_inputs["A"], npu_inputs["W"])
    bias_scale = npu_inputs["activation_scale"] * npu_inputs["weight_scale"]
    bias_scaled = [int(round(float(value) * bias_scale)) for value in npu_inputs["bias"]]
    scaled_logits = [int(acc[0][idx]) + bias_scaled[idx] for idx in range(REAL_CLASSES)]
    quantized_prediction = max(range(REAL_CLASSES), key=lambda idx: scaled_logits[idx])
    if quantized_prediction != expected_label:
        raise ValueError(
            f"quantized MNIST fc2 sample {sample_index} predicts {quantized_prediction}, expected {expected_label}"
        )

    lines.append("#define REAL_MNIST_CNN_FC2_ENABLED 1u")
    lines.append(f"#define REAL_MNIST_CNN_FC2_SAMPLE_INDEX {sample_index}u")
    lines.append(f"#define REAL_MNIST_CNN_FC2_TILE_COUNT {len(jobs)}u")
    lines.append("#define REAL_MNIST_CNN_FC2_TILE_WORDS 64u")
    lines.append(f"#define REAL_MNIST_CNN_FC2_LOGITS_WORDS {len(acc) * len(acc[0])}u")
    lines.append(f"#define REAL_MNIST_CNN_FC2_CLASS_COUNT {REAL_CLASSES}u")
    lines.append(f"#define REAL_MNIST_CNN_FC2_CLASS_COLUMNS {CLASS_COLUMNS}u")
    lines.append(f"#define REAL_MNIST_CNN_FC2_EXPECTED_LABEL {expected_label}u")
    lines.append("")

    _append_2d_array(lines, "real_mnist_cnn_fc2_tile_n_offsets", [[job["n_offset"] for job in jobs]], bits=32)
    _append_2d_array(lines, "real_mnist_cnn_fc2_tile_a", [job["inputs"]["A"] for job in jobs], bits=8)
    _append_2d_array(lines, "real_mnist_cnn_fc2_tile_b", [job["inputs"]["B"] for job in jobs], bits=8)
    _append_flat_array(lines, "real_mnist_cnn_fc2_bias_scaled", bias_scaled, bits=32)
    _append_flat_array(lines, "real_mnist_cnn_fc2_expected_scaled_logits", scaled_logits, bits=32)
    return len(jobs)


def _write_workload_manifest(
    path: Path,
    digits_jobs: int,
    fc1_tile_jobs: int,
    fc1_k_stream_jobs: int,
    fc1_full_jobs: int,
    fc1_full_k_chunks: int,
    fc2_jobs: int,
) -> None:
    jobs: list[dict] = []

    def add(workload: str, op: str, role: str, count: int, tiled: bool = False) -> None:
        for tile_id in range(count):
            item = {
                "job_id": len(jobs) + 1,
                "workload": workload,
                "op": op,
                "role": role,
            }
            if tiled:
                item["tile_id"] = tile_id
            jobs.append(item)

    add("operator_smoke_matmul", "matmul", "smoke", 1)
    add("operator_smoke_softmax", "softmax", "smoke", 1)
    add("digits_linear_classifier", "matmul", "regression", digits_jobs, tiled=True)
    add("real_mnist_cnn_fc1_tile0", "matmul", "regression", fc1_tile_jobs, tiled=True)
    add(
        "real_mnist_cnn_fc1_k_stream_smoke",
        "matmul_k_stream",
        "regression",
        fc1_k_stream_jobs,
        tiled=True,
    )
    add(
        "real_mnist_cnn_fc1_full_k_stream_layer",
        "matmul_k_stream",
        "regression",
        fc1_full_jobs,
        tiled=True,
    )
    add("real_mnist_cnn_fc2", "matmul", "regression", fc2_jobs, tiled=True)
    manifest = {
        "schema": "npu_workload_manifest_v0",
        "manifest_id": "soc_cpu_smoke_v0",
        "run_name": "soc_cpu_smoke",
        "generated_by": "sw/tools/firmware/emit_soc_cpu_smoke_data.py",
        "workload_metadata": {
            "operator_smoke_matmul": {"kind": "operator_smoke"},
            "operator_smoke_softmax": {"kind": "operator_smoke"},
            "digits_linear_classifier": {
                "kind": "model",
                "metadata": {
                    "input": "test/assets/digits_realistic/digit_2_gray.pgm",
                    "graph": "test/graphs/digits_classifier.json",
                    "tile_graph": "test/graphs/digits_classifier_rtl_tile.json",
                    "tile_jobs": digits_jobs,
                    "description": "8x8 grayscale digit image, tiled matmul regression with CPU-side accumulation",
                },
            },
            "real_mnist_cnn_fc1_tile0": {
                "kind": "model_layer_tile",
                "metadata": {"tile_jobs": fc1_tile_jobs},
            },
            "real_mnist_cnn_fc1_k_stream_smoke": {
                "kind": "model_layer_tile",
                "metadata": {"tile_jobs": fc1_k_stream_jobs},
            },
            "real_mnist_cnn_fc1_full_k_stream_layer": {
                "kind": "model_layer",
                "metadata": {"tile_jobs": fc1_full_jobs, "k_chunks": fc1_full_k_chunks},
            },
            "real_mnist_cnn_fc2": {
                "kind": "model_layer",
                "metadata": {"tile_jobs": fc2_jobs},
            },
        },
        "jobs": jobs,
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")


def _append_2d_array(lines: list[str], symbol: str, values: list, bits: int) -> None:
    if symbol == "digits_tile_n_offsets":
        flat_rows = values
        row_len = len(values[0])
    else:
        flat_rows = [_flatten(item) for item in values]
        row_len = len(flat_rows[0])
    lines.append(f"static const uint32_t {symbol}[{len(flat_rows)}][{row_len}] = {{")
    mask = (1 << bits) - 1
    for row in flat_rows:
        lines.append("    {" + ", ".join(f"0x{(int(value) & mask):08x}u" for value in row) + "},")
    lines.append("};")
    lines.append("")


def _append_3d_array(lines: list[str], symbol: str, values: list, bits: int) -> None:
    flat_planes = [[_flatten(row) for row in plane] for plane in values]
    rows = len(flat_planes[0])
    cols = len(flat_planes[0][0])
    mask = (1 << bits) - 1
    lines.append(f"static const uint32_t {symbol}[{len(flat_planes)}][{rows}][{cols}] = {{")
    for plane in flat_planes:
        lines.append("    {")
        for row in plane:
            lines.append("        {" + ", ".join(f"0x{(int(value) & mask):08x}u" for value in row) + "},")
        lines.append("    },")
    lines.append("};")
    lines.append("")


def _append_flat_array(lines: list[str], symbol: str, values: list[int], bits: int) -> None:
    mask = (1 << bits) - 1
    lines.append(f"static const uint32_t {symbol}[{len(values)}] = {{")
    for value in values:
        lines.append(f"    0x{(int(value) & mask):08x}u,")
    lines.append("};")
    lines.append("")


def _flatten(value):
    out = []
    for item in value:
        if isinstance(item, list):
            out.extend(_flatten(item))
        else:
            out.append(item)
    return out


if __name__ == "__main__":
    main()
